/**
 * Generates src/text/metrics.ts: advance widths for the faces the renderers
 * use, read from the bundled metric-compatible fonts (Arimo = Arial,
 * Carlito = Calibri).
 *
 * Run: npx tsx scripts/gen-metrics.ts
 */
import { writeFileSync } from "node:fs";
import { loadFont } from "./lib/ttf.js";

const OUT = "src/text/metrics.ts";
const FACES = {
  arial: "assets/fonts/Arimo_400Regular.ttf",
  arialBold: "assets/fonts/Arimo_700Bold.ttf",
  arialItalic: "assets/fonts/Arimo_400Regular_Italic.ttf",
  calibri: "assets/fonts/Carlito_400Regular.ttf",
  calibriBold: "assets/fonts/Carlito_700Bold.ttf",
} as const;

// Printable ASCII, Latin-1 letters (Spanish, Tagalog), dashes, quotes, arrows.
const CPS = [
  ...Array.from({ length: 95 }, (_, i) => 32 + i),
  ...Array.from({ length: 96 }, (_, i) => 0xa0 + i),
  0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026, 0x2191, 0x2193, 0x266f,
];

const tables = Object.entries(FACES).map(([face, file]) => {
  const font = loadFont(file);
  const widths: Record<string, number> = {};
  for (const cp of CPS) {
    const w = font.advance(cp);
    if (w !== undefined) widths[String.fromCodePoint(cp)] = w;
  }
  return { face, file, widths };
});

const body = tables
  .map(({ face, file, widths }) =>
    `  /** ${file} */\n  ${face}: {\n${Object.entries(widths).map(([ch, w]) => `    ${JSON.stringify(ch)}: ${w},`).join("\n")}\n  },`)
  .join("\n");

writeFileSync(
  OUT,
  `// Generated by scripts/gen-metrics.ts. Do not edit.
// Advance widths in 1/1000 em. Arimo is metric-compatible with Arial, Carlito with Calibri.
export type Face = ${Object.keys(FACES).map((f) => JSON.stringify(f)).join(" | ")};

export const ADVANCE: Readonly<Record<Face, Readonly<Record<string, number>>>> = {
${body}
};

/** Fallback for characters not in a table. */
export const DEFAULT_ADVANCE = 556;

/** Width of \`text\` at \`fontSize\` in the given face, without kerning. */
export function textWidth(text: string, fontSize: number, face: Face = "arial"): number {
  const table = ADVANCE[face];
  let w = 0;
  for (const ch of text) w += table[ch] ?? DEFAULT_ADVANCE;
  return (w * fontSize) / 1000;
}
`,
);
console.log(`wrote ${OUT}:`, tables.map((t) => `${t.face} ${Object.keys(t.widths).length}`).join(", "));
