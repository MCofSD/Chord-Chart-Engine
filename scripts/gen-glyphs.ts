/**
 * Generates src/text/glyphs.ts: outlines for symbols that the text fonts
 * (Arimo, Carlito) lack or that must look identical everywhere. Drawn as
 * SVG paths, so no renderer needs these fonts.
 *
 * Run: npx tsx scripts/gen-glyphs.ts
 */
import { writeFileSync } from "node:fs";
import { basename } from "node:path";
import { loadFont, type GlyphOutline } from "./lib/ttf.js";

const OUT = "src/text/glyphs.ts";
const MUSIC = "assets/fonts/NotoMusic_400Regular.ttf";
const MATH = "assets/fonts/NotoSansMath_400Regular.ttf";
const CARLITO = "assets/fonts/Carlito_400Regular.ttf";

const SOURCES: [name: string, file: string, cp: number, note: string][] = [
  ["FLAT", MUSIC, 0x266d, "♭"],
  ["SHARP", MUSIC, 0x266f, "♯"],
  ["CIRCLED_PLUS", MATH, 0x2295, "⊕ (Legend: only)"],
  ["CIRCLED_TIMES", MATH, 0x2297, "⊗ (Legend: except)"],
];
// ❶-❿: the blue circled riff-reference numbers (Wingdings in the originals).
for (let n = 1; n <= 10; n++) SOURCES.push([`NEG_CIRCLED_${n}`, CARLITO, 0x2775 + n, String.fromCodePoint(0x2775 + n)]);

const fonts = new Map<string, ReturnType<typeof loadFont>>();
const out: string[] = [];
for (const [name, file, cp, note] of SOURCES) {
  if (!fonts.has(file)) fonts.set(file, loadFont(file));
  const g: GlyphOutline = fonts.get(file)!.outline(cp);
  out.push(`/** ${note}, from ${basename(file)} */\nexport const ${name}: GlyphOutline = ${JSON.stringify(g)};`);
}

writeFileSync(
  OUT,
  `// Generated by scripts/gen-glyphs.ts from SIL OFL fonts in assets/fonts. Do not edit.
// Paths are in 1/1000 em, y pointing down, baseline at y = 0, origin at the glyph's left edge.
export interface GlyphOutline {
  path: string;
  advance: number;
  /** Ink box in 1/1000 em, y up from baseline. */
  xMin: number; xMax: number; yMin: number; yMax: number;
}

${out.join("\n\n")}

export const NEG_CIRCLED: readonly GlyphOutline[] = [${Array.from({ length: 10 }, (_, i) => `NEG_CIRCLED_${i + 1}`).join(", ")}];
`,
);
console.log(`wrote ${OUT}: ${SOURCES.length} glyphs`);
